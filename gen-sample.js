// 生成示例需求 Excel 文件（每个 xlsx = 一个需求）
// 列：用例编号 / 验证名称 / 优先级 / 用例类型 / 前置条件 / 操作步骤 / 预期结果 / 测试结果
const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, 'cases-sample');
const HEAD = ['用例编号', '验证名称', '优先级', '用例类型', '前置条件', '操作步骤', '预期结果', '测试结果'];

function build(name, rows) {
  const data = [HEAD, ...rows];
  const ws = XLSX.utils.aoa_to_sheet(data);
  ws['!cols'] = [{ wch: 10 }, { wch: 22 }, { wch: 8 }, { wch: 10 }, { wch: 18 }, { wch: 28 }, { wch: 24 }, { wch: 10 }];
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, '用例');
  const file = path.join(OUT, name + '.xlsx');
  XLSX.writeFile(wb, file);
  console.log('生成:', file, '用例数', rows.length);
}

